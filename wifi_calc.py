def _ccw(A,B,C): return (C[1]-A[1])*(B[0]-A[0])-(B[1]-A[1])*(C[0]-A[0])
def cross_n(a,b,p,q):
    """число пересечений отрезка p-q со стеной a-b"""
    if _ccw(a,b,p)==_ccw(a,b,q) or _ccw(p,q,a)==_ccw(p,q,b): return 0
    return 1

def n_walls(p,q):
    n=0
    for a,b in segs: n+=cross_n(a,b,p,q)
    return n

# --- радиомодель ---
def rss(ptx_dbm,f_mhz,d,st):
    d=max(float(d),0.5)
    fspl=32.44+20*math.log10(f_mhz)+20*math.log10(d/1000.0)
    n_exp=2.7 if f_mhz==2400 else 3.0
    att=12 if f_mhz==2400 else 20  # ЖБ 200 мм с базальтом/армированием
    L=ptx_dbm-fspl+(n_exp-2)*10*math.log10(d)-st*att
    return L

